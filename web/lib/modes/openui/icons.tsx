export function iconTint(name: string): string {
  const key = name.toLowerCase()
  if (ICON_TINT[key]) return ICON_TINT[key]
  let hash = 0
  for (let i = 0; i < key.length; i++) hash = (hash * 31 + key.charCodeAt(i)) | 0
  return BADGE_COLORS[Math.abs(hash) % BADGE_COLORS.length]
}

export function LucideIcon({
  name,
  size = 17,
  strokeWidth = 2,
  color,
}: {
  name: string
  size?: number
  strokeWidth?: number
  color: string
}) {
  const Icon = ICONS[name.toLowerCase()]
  if (!Icon) {
    const dot: CSSProperties = { width: 8, height: 8, borderRadius: 4, backgroundColor: color, opacity: 0.6, display: "inline-block" }
    return <span style={dot} />
  }
  return <Icon size={size} strokeWidth={strokeWidth} color={color} />
}
